#!/usr/bin/env python3
"""Rasterise the lab's crisp 2x font into `src/hud_crisp.rs`.

The lab's interface layer (`render::Hud::layer`) is drawn at twice the
logical resolution, and its text uses this table instead of the 5x7 dot
matrix blown up. **Same character grid as the 5x7 font**: a glyph owns a
12x14 cell at 2x (the 6-pixel advance and 7-pixel height of `hud.rs`,
doubled), so every page keeps its layout, every hit box keeps its size and
the overlap census's text rectangles stay true. Ink is held to columns
0..=10 and rows 0..=13 of the cell, the box a doubled 5x7 glyph fills plus
one column, so no glyph reaches its neighbour.

Capitals only, for the reason `hud.rs` gives: every string in the code is
written in capitals, and the set is exactly `hud::has_glyph`'s.

    python3 scripts/crispfont.py                 # rewrite src/hud_crisp.rs
    python3 scripts/crispfont.py --preview x.png # and draw the set, 4x

The face is JetBrains Mono (SIL Open Font License 1.1); only its
rasterised coverage is shipped, never the font file. Rendered at 8x and
box-filtered down, so coverage is exact area rather than PIL's hinted
outline, which at 14 px rounds stems unevenly from letter to letter.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/jetbrains-mono/JetBrainsMono-SemiBold.ttf"
CELL_W, CELL_H = 12, 14
INK_W = 11  # columns 0..=10 may carry ink
CAP_H = 14.0  # cap height in output pixels
SS = 8  # supersample factor

# hud::has_glyph's set, in hud.rs's order.
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:-/%()[]!?+=*_<>;'`\\"


def render(font_path, cap_h):
    probe = ImageFont.truetype(font_path, 100 * SS)
    box = probe.getbbox("H", anchor="ls")
    size = 100 * SS * cap_h * SS / (box[3] - box[1])
    font = ImageFont.truetype(font_path, int(round(size)))
    adv = font.getlength("H")
    baseline = int(round(cap_h * SS))
    glyphs = {}
    for c in CHARS:
        # Drawn on a canvas a cell taller each way, so a glyph that rises
        # above a capital or drops below the baseline is measured whole
        # before it is fitted, not clipped by the canvas.
        pad = CELL_H * SS
        big = Image.new("L", (CELL_W * SS, CELL_H * SS + 2 * pad), 0)
        d = ImageDraw.Draw(big)
        # The advance box centred on the ink columns, so narrow glyphs keep
        # the face's own spacing rather than being pulled to the left edge.
        x = (INK_W * SS - adv) / 2
        d.text((x, baseline + pad), c, fill=255, font=font, anchor="ls")
        bbox = big.getbbox()
        # Descenders (`,` `;` `_`) are lifted to sit inside the cell rather
        # than cut, and the few glyphs taller than a capital (`[` `]` `(` `)`)
        # are squeezed to the cell's height: the 5x7 font has no row above or
        # below a capital either.
        if not bbox:
            big = Image.new("L", (CELL_W * SS, CELL_H * SS), 0)
        else:
            ink = big.crop(bbox)
            h = bbox[3] - bbox[1]
            if h > CELL_H * SS:
                ink = ink.resize((ink.width, CELL_H * SS), Image.LANCZOS)
                top = 0
            else:
                top = min(max(bbox[1] - pad, 0), CELL_H * SS - h)
            big = Image.new("L", (CELL_W * SS, CELL_H * SS), 0)
            big.paste(ink, (bbox[0], top))
        small = big.resize((CELL_W, CELL_H), Image.BOX)
        px = list(small.tobytes())
        for row in range(CELL_H):
            for col in range(INK_W, CELL_W):
                px[row * CELL_W + col] = 0
        glyphs[c] = px
    return glyphs


def rust_literal(c):
    if c == "'":
        return "'\\''"
    if c == "\\":
        return "'\\\\'"
    return f"'{c}'"


def write_rs(glyphs, path):
    out = []
    out.append("//! **Generated by `scripts/crispfont.py` -- do not edit by hand.**")
    out.append("//!")
    out.append("//! Coverage (0-255) for the lab's crisp 2x text, one 12x14 cell per glyph on")
    out.append("//! the 5x7 font's own grid doubled -- see `hud::draw_text_crisp`. Rasterised")
    out.append("//! from JetBrains Mono SemiBold (SIL Open Font License 1.1).")
    out.append("")
    out.append(f"pub const CELL_W: usize = {CELL_W};")
    out.append(f"pub const CELL_H: usize = {CELL_H};")
    out.append("")
    out.append("pub fn coverage(c: char) -> Option<&'static [u8; CELL_W * CELL_H]> {")
    out.append("    Some(match c {")
    for i, c in enumerate(CHARS):
        out.append(f"        {rust_literal(c)} => &GLYPHS[{i}],")
    out.append("        _ => return None,")
    out.append("    })")
    out.append("}")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"static GLYPHS: [[u8; CELL_W * CELL_H]; {len(CHARS)}] = [")
    for c in CHARS:
        px = glyphs[c]
        out.append(f"    // {c}")
        out.append("    [")
        for row in range(CELL_H):
            out.append("        " + ", ".join(f"{v:3}" for v in px[row * CELL_W:(row + 1) * CELL_W]) + ",")
        out.append("    ],")
    out.append("];")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def preview(glyphs, path, scale=4):
    cols = 20
    rows = (len(CHARS) + cols - 1) // cols
    img = Image.new("RGB", (cols * CELL_W * scale, rows * CELL_H * scale), (16, 18, 24))
    for i, c in enumerate(CHARS):
        gx, gy = (i % cols) * CELL_W, (i // cols) * CELL_H
        for row in range(CELL_H):
            for col in range(CELL_W):
                v = glyphs[c][row * CELL_W + col]
                if v:
                    for sy in range(scale):
                        for sx in range(scale):
                            img.putpixel(((gx + col) * scale + sx, (gy + row) * scale + sy), (v, v, v))
    img.save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=FONT)
    ap.add_argument("--cap", type=float, default=CAP_H)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "hud_crisp.rs"))
    ap.add_argument("--preview")
    a = ap.parse_args()
    if not os.path.exists(a.font):
        sys.exit(f"font not found: {a.font}")
    glyphs = render(a.font, a.cap)
    write_rs(glyphs, a.out)
    if a.preview:
        preview(glyphs, a.preview)


if __name__ == "__main__":
    main()
